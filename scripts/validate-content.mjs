import fs from 'node:fs';
import assert from 'node:assert/strict';
import {validateCourse} from '../src/engine/model.ts';
import {validateTeacherPack,validateBank,courseAssets} from '../src/engine/validation.ts';
import {evaluate} from '../src/engine/scoring.ts';
import {validateNarrative} from './narrative-structure.mjs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const course=read('public/course.json'),pack=read('public/teacher-pack.json'),bank=read('public/assessment.json'),models=read('public/workbenches.json'),coverage=read('authoring/coverage.json');
validateCourse(course);validateTeacherPack(pack,course);validateBank(bank,course);
assert.deepEqual(course.semesters,[5,6]);assert.ok(!course.year);
assert.deepEqual(course.assessment,{mode:'autonomous',url:'assessment.json'});
assert.equal(coverage.filter(c=>c.category==='lecture').length,17);
assert.equal(coverage.filter(c=>c.category==='laboratory').length,12);
for(const [semester,lectures,labs] of [[5,10,7],[6,7,5]]){
 assert.equal(coverage.filter(c=>c.semester===semester&&c.category==='lecture').length,lectures);
 assert.equal(coverage.filter(c=>c.semester===semester&&c.category==='laboratory').length,labs);
}
for(const path of courseAssets(course))if(!/^https?:/.test(path))assert.ok(fs.existsSync('public/'+path),path);
for(const lecture of course.lectures){
 assert.equal(lecture.slides[0].kind,'title');
 const outline=coverage.find(c=>c.lectureId===lecture.id);
 if(outline.category==='lecture'){
  validateNarrative(lecture,outline);
 }
 for(const slide of lecture.slides){
  assert.ok(pack.notes[slide.id]?.script.trim(),slide.id);
  assert.ok(!/3г10|2г10|2026.2027|Generated by|Co-authored-by/.test(JSON.stringify(slide)),slide.id);
  if(slide.learning){
   const model=models[slide.learning.id];assert.ok(model,slide.id);assert.equal(model.scenarios.length,2);
   for(const scenario of model.scenarios){assert.ok(scenario.frames.length>=4);assert.ok(scenario.accepted.length);assert.ok(scenario.review);}
  }
  if(slide.task){
   const key=bank.keys[slide.task.id];
   const answer=slide.task.type==='multiple'?key.correct:(key.correct?.[0]??key.accepted?.[0]);assert.equal(evaluate(slide.task,key,answer).status,'correct');
   assert.equal(evaluate(slide.task,key,'несуществующий ответ').status,'incorrect');
  }
 }
}
// The rejected one-question course and an absent discussion must not pass again.
const sample=course.lectures.find(l=>coverage.find(c=>c.lectureId===l.id).category==='lecture');
const planned=coverage.find(c=>c.lectureId===sample.id);
const collapsed=structuredClone(sample);let seenQuestion=false;
collapsed.slides=collapsed.slides.filter(s=>{if(s.kind!=='section')return true;if(seenQuestion)return false;seenQuestion=true;return true});
assert.throws(()=>validateNarrative(collapsed,planned),/questions do not match/);
assert.throws(()=>validateNarrative({...sample,slides:sample.slides.filter(s=>s.kind!=='questions')},planned),/discussion must conclude/);
// Independent arithmetic checks against the authored quantities, not snapshots of rendered text.
assert.equal(8+2+1,11);assert.equal(4*12>45,true);
assert.equal(1200/6,200);assert.equal([1,2,1,3,2,3].reduce((a,b)=>a+b)/6,2);
assert.ok(Math.abs(Math.exp(-20/200)-.904837418)<1e-8);
assert.equal(900/(900+20+80),.9);
assert.ok(Math.abs(.98*(1-.05**2)-.97755)<1e-12);
assert.ok(Math.abs(.97*(1-.08**2)*.96-.92524032)<1e-12);
assert.equal(1-8/200,.96);
const a=[120,120,130,130,140,150,160,180,300,900],b=[100,100,110,110,120,120,130,140,160,300];
assert.equal(a.reduce((x,y)=>x+y)/a.length,233);assert.equal(b.reduce((x,y)=>x+y)/b.length,139);
assert.equal(a[Math.ceil(.95*a.length)-1],900);
console.log(JSON.stringify({lectures:17,laboratories:12,slides:Object.keys(pack.notes).length,models:Object.keys(models).length,tasks:Object.keys(bank.keys).length}));
